import type { Step, Tour } from '../tours';

/** บทสอน — see tours.ts for the target syntax and the rules every tour follows */

/** a folded filter bar (phones start folded): its fields are inert → their steps drop out — open it, then ? again */
const FILTER_TOGGLE: Step = {
  target: 'main div.surface.no-print > button[aria-expanded="false"]',
  title: 'ตัวกรอง',
  body: 'ตัวกรองพับอยู่ (บนมือถือพับไว้ตั้งแต่เปิดหน้า) — จบบทสอนแล้วแตะ "แสดงตัวกรอง" ที่แถบนี้ แล้วกด ? อีกครั้ง เพื่อดูวิธีใช้ช่องค้นหา',
  look: true,
};

const ROW1 = 'main tbody tr:first-child';
const ACTIONS = `${ROW1} td:last-child`;

const exportStep = (body: string): Step => ({ target: 'button:ส่งออก Excel', title: 'ส่งออก Excel', body, look: true });

/** the button that opens the add dialog, lit where it is on the page — its dialog's steps come at the end */
const addStep = (button: string, what: string): Step => ({
  target: `button:${button}`,
  title: button,
  body: `เปิดหน้าต่าง${what} — บทสอนเปิดหน้าต่างนี้ให้ดูทีละช่องตอนท้าย`,
  look: true,
});

/** a button of an add dialog that saves: looked at, never pressed */
const saveStep = (button: string, body: string): Step => ({
  target: `button:${button}`,
  title: button,
  body,
  look: true,
});

/** steps inside the dialog that `open` (a button on the page) shows */
const inDialog = (open: string, steps: Step[]): Step[] => steps.map((s) => ({ ...s, dialog: { open } }));

/* ------------------------------------------------------------------ *
 * ข้อมูลหลัก — หมวดหมู่ / ยี่ห้อ / สี / ประเภทงาน / ประเภทเครื่อง / อาการเสีย (MasterTable) and รุ่นสินค้า
 * (its own page, the same shape): one factory, the differences as parameters
 * ------------------------------------------------------------------ */
type MasterPage = {
  /** the page heading */
  title: string;
  /** the welcome card: what the list is, where it shows up */
  welcome: string;
  /** the button that opens the add dialog */
  add: string;
  /** the filter fields (`field:a|b`) and what to type in them */
  filter: { target: string; body: string };
  /** the six simple lists: รายการที่ลบ, a status switch on each row, ลบ — รุ่นสินค้า has none of these */
  simple: boolean;
  /** the row buttons */
  actions: string;
  /** the add dialog's fields in reading order */
  form: Step[];
};

function masterTour(p: MasterPage): Tour {
  const steps: Step[] = [
    { title: `จัดการ${p.title}`, body: p.welcome },
    exportStep('ดาวน์โหลดรายการตามตัวกรองที่ค้นหาแล้วเป็นไฟล์ Excel (ไม่รวมรายการที่ลบ)'),
    addStep(p.add, `เพิ่ม${p.title}ใหม่`),
  ];
  if (p.simple)
    steps.push({
      target: 'button:รายการที่ลบ',
      title: 'รายการที่ลบ',
      body: 'รายการที่ถูกลบอยู่ในแท็บนี้ — กด กู้คืน ที่แถวนั้น รายการกลับมาเป็น Active และเป็นตัวเลือกในฟอร์มอีกครั้ง · กด รายการ เพื่อกลับ',
      look: true,
    });
  steps.push(FILTER_TOGGLE, { target: p.filter.target, title: 'ค้นหา', body: p.filter.body, look: true });
  if (p.simple)
    steps.push({
      target: `${ROW1} [role="switch"]`,
      title: 'สถานะ Active / Inactive',
      body: 'กดป้ายสถานะเพื่อสลับ (ระบบถามยืนยันก่อน) · Inactive = ไม่แสดงเป็นตัวเลือกเมื่อกรอกข้อมูลใหม่ ข้อมูลเดิมยังอยู่และแสดงชื่อเดิม — ใช้เมื่อหยุดใช้ชั่วคราว',
      look: true,
    });
  steps.push(
    { target: ACTIONS, title: p.simple ? 'แก้ไข / ลบ' : 'ดู / แก้ไข', body: p.actions, look: true },
    ...inDialog(`button:${p.add}`, [
      ...p.form,
      saveStep(
        'บันทึกข้อมูล',
        'บันทึกแล้วหน้าต่างปิดและรายการขึ้นในตาราง · กรอกไม่ครบหรือชื่อซ้ำ ระบบแจ้งใต้ช่องนั้น · ยกเลิก หรือ ✕ = ปิดโดยไม่บันทึก',
      ),
    ]),
  );
  return { title: p.title, steps };
}

/** the six simple lists: name + status, maybe SLA / group, maybe รายละเอียด */
function simpleList(o: {
  title: string;
  welcome: string;
  nameLabel: string;
  example: string;
  /** รายละเอียด's length (MASTER_DETAIL_MAX) — none: the list has no รายละเอียด */
  detailMax?: number;
  extra?: Step[];
}): Tour {
  const form: Step[] = [
    {
      target: `field:${o.nameLabel}|สถานะ`,
      title: `${o.nameLabel}และสถานะ *`,
      body: `${o.nameLabel}: ไม่เกิน 50 ตัวอักษร ห้ามซ้ำ (ไม่สนตัวพิมพ์เล็ก-ใหญ่และช่องว่าง รวมรายการ Inactive และที่ลบ) — ซ้ำกับรายการที่ลบ ให้กู้คืนรายการนั้นแทน · สถานะ: Active = เป็นตัวเลือกในฟอร์ม`,
      example: o.example,
    },
    ...(o.extra ?? []),
  ];
  if (o.detailMax)
    form.push({ target: 'field:รายละเอียด', title: 'รายละเอียด', body: `ไม่บังคับ ไม่เกิน ${o.detailMax} ตัวอักษร` });
  return masterTour({
    title: o.title,
    welcome: `${o.welcome} · ลองพิมพ์ในหน้าต่างเพิ่มข้อมูลได้ ไม่มีอะไรถูกบันทึก`,
    add: 'เพิ่มข้อมูล',
    simple: true,
    filter: {
      target: `field:${o.nameLabel}|สถานะ`,
      body: `${o.nameLabel}: พิมพ์บางส่วนของชื่อ · สถานะ: Active / Inactive — แล้วกด ค้นหา (หรือ Enter) · ล้างค่า = แสดงทั้งหมด`,
    },
    actions:
      'แก้ไข (ดินสอ): เปิดหน้าต่างแก้ไข · ลบ (ถังขยะ): รายการหายจากหน้านี้และจากตัวเลือกเมื่อกรอกข้อมูลใหม่ ลบได้แม้มีงานหรือเอกสารที่ใช้ค่านี้อยู่ ข้อมูลเดิมยังแสดงชื่อเดิม และกู้คืนได้จากแท็บ รายการที่ลบ',
    form,
  });
}

