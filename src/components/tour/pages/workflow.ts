/** the welcome card: what this page is for, then try it — or, view only, look */
const intro =
  (what: string, page: Module) =>
  ({ can }: StepCtx) =>
    `${what} · ${can(page, 'edit') ? TRY : 'บัญชีนี้ดูได้อย่างเดียว บทสอนพาดูว่าแต่ละส่วนคืออะไร'}`;

/** RecordGate's lookup failed: its "ค้นหาใหม่" button is shown in the form's place — the phase-1 card says so */
export const GATE_ERROR = 'button:ค้นหาใหม่';
export const gateError = (noun: string) =>
  `เรียก${noun}ไม่สำเร็จ (เหตุผลแสดงบนหน้า) — จบบทสอนแล้วกด "ค้นหาใหม่" บนหน้า เรียกอีกครั้ง แล้วกด ? อีกครั้ง`;

/**
 * The job search in the page header — two phases: no job yet (how to call one up, then ? again) / a job loaded
 * (another one). View only: a job picked during the tour would be overwritten by the form put back at its end.
 */
function search(label: string, offered: string, extra = ''): Step[] {
  return [
    {
      target: `field:${label}`,
      show: ({ has }) => !has(LOADED),
      title: 'เรียกงานขึ้นมาก่อน',
      body: ({ has }) =>
        has(GATE_ERROR)
          ? gateError('งาน')
          : `กดช่องค้นหา พิมพ์เลขงาน ชื่อ/เบอร์ลูกค้า หรือ Serial อย่างน้อย 3 ตัว แล้วเลือกงาน (${offered}) หรือพิมพ์เลขงานเต็มแล้วกด Enter · เรียกงานแล้วกด ? อีกครั้ง`,
      example: 'J2612164 หรือ 0812345678',
      look: true,
    },
    {
      target: `field:${label}`,
      show: ({ has }) => has(LOADED),
      title: 'เรียกงานอื่น',
      body: `งานที่แสดงอยู่เรียกจากช่องนี้ เปลี่ยนงานได้ที่ช่องเดียวกัน (${offered})${extra}`,
      look: true,
    },
  ];
}

