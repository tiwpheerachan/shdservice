-- 0000_init — every migration of the app in one file (0000_baseline … 0039_app_user_tour, squashed 2026-10-27).
-- Each part keeps its original file name as a `-- >>> <name>.sql` line (scripts/test-domain.mts reads a part
-- by it) and is IDEMPOTENT as before: a database that ran the 40 files records 0000_init as applied already
-- (its journal time is 0039's), a fresh one — or one whose legacy tables were reloaded (scripts/migrate.ts
-- clears the journal) — runs this file. The 40 files are in git history before this commit.

-- >>> 0000_baseline.sql
-- 0000_baseline — the legacy SHDElectronicServiceDB schema (52 tables) exactly as
-- produced by setupdata/convert.py, rewritten to be IDEMPOTENT so it can run on a
-- database that already holds the loaded dump (no-op) or on an empty one.
-- Re-runnable after every re-dump/reload. Data is NOT part of this migration:
-- load it with setupdata/load_supabase.sh.

